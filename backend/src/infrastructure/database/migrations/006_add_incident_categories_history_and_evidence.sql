CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS categories (
  code VARCHAR(30) PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE
);

INSERT INTO categories (code, name)
VALUES
  ('bache', 'Bache'),
  ('alumbrado', 'Alumbrado público'),
  ('basura', 'Basura')
ON CONFLICT (code) DO UPDATE
SET name = EXCLUDED.name;

ALTER TABLE incidents
  ADD COLUMN IF NOT EXISTS category_code VARCHAR(30)
  REFERENCES categories(code) ON UPDATE CASCADE ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS incidents_category_created_idx
  ON incidents (category_code, created_at DESC);

CREATE TABLE IF NOT EXISTS incident_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id UUID NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
  previous_status VARCHAR(30),
  new_status VARCHAR(30) NOT NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  changed_by UUID REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS incident_status_history_incident_changed_idx
  ON incident_status_history (incident_id, changed_at DESC, id DESC);

INSERT INTO incident_status_history
  (incident_id, previous_status, new_status, changed_at, changed_by)
SELECT incidents.id, NULL, incidents.status, incidents.created_at, incidents.created_by
FROM incidents
WHERE NOT EXISTS (
  SELECT 1
  FROM incident_status_history AS history
  WHERE history.incident_id = incidents.id
);

CREATE TABLE IF NOT EXISTS evidences (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  incident_id UUID NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
  photo_url TEXT NOT NULL CHECK (length(trim(photo_url)) > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS evidences_incident_created_idx
  ON evidences (incident_id, created_at DESC);

CREATE INDEX IF NOT EXISTS incidents_location_gist_idx
  ON incidents USING GIST (location)
  WHERE location IS NOT NULL;

CREATE OR REPLACE FUNCTION require_category_for_new_incident()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.category_code IS NULL THEN
    RAISE EXCEPTION 'La categoría es obligatoria para las nuevas incidencias.'
      USING ERRCODE = '23502';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS incidents_require_category_on_insert ON incidents;
CREATE TRIGGER incidents_require_category_on_insert
  BEFORE INSERT ON incidents
  FOR EACH ROW
  EXECUTE FUNCTION require_category_for_new_incident();
