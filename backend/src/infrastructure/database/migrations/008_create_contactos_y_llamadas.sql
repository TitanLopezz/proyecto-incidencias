-- Tabla de contactos del equipo de atención
CREATE TABLE IF NOT EXISTS contactos_equipo (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre      VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0),
  equipo      VARCHAR(120) NOT NULL CHECK (length(trim(equipo)) > 0),
  tipo_incidencia VARCHAR(30) REFERENCES categories(code) ON UPDATE CASCADE ON DELETE SET NULL,
  telefono    VARCHAR(20)  NOT NULL CHECK (telefono ~ '^\+?[0-9]{7,15}$'),
  correo      VARCHAR(254),
  horario     VARCHAR(120),
  activo      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS contactos_equipo_tipo_idx
  ON contactos_equipo (tipo_incidencia);

CREATE INDEX IF NOT EXISTS contactos_equipo_activo_idx
  ON contactos_equipo (activo);

-- Tabla de historial de avisos/llamadas al equipo
CREATE TABLE IF NOT EXISTS llamadas_equipo (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id     UUID REFERENCES incidents(id) ON DELETE SET NULL,
  contacto_id     UUID NOT NULL REFERENCES contactos_equipo(id) ON DELETE CASCADE,
  admin_id        UUID REFERENCES users(id) ON DELETE SET NULL,
  canal           VARCHAR(20) NOT NULL CHECK (canal IN ('telefono', 'whatsapp')),
  notas           TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS llamadas_equipo_incident_idx
  ON llamadas_equipo (incident_id, created_at DESC);

CREATE INDEX IF NOT EXISTS llamadas_equipo_contacto_idx
  ON llamadas_equipo (contacto_id, created_at DESC);

CREATE INDEX IF NOT EXISTS llamadas_equipo_admin_idx
  ON llamadas_equipo (admin_id, created_at DESC);
